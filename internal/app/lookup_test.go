func lookupSetup(t *testing.T, urls ...string) (*testEnv, *kpxtest.Server) {
	t.Helper()
	fake := newFake()
	fake.Entries = []kpxtest.Entry{
		{Entry: kpx.Entry{UUID: uuidA, Name: "hcloud s1 token", Login: "me", Password: "PW-SECRET-1", Group: "Root/Cloud",
			Fields: map[string]string{"KPH: HCLOUD_TOKEN": "FIELD-SECRET-2", "other": "x"}}, URLs: urls},
		{Entry: kpx.Entry{UUID: uuidB, Name: "old", Password: "PW-SECRET-3", TOTP: "t", Expired: true}, URLs: urls},
	}
	te := newTestEnv(t, fake)
	if code := Main([]string{"associate"}, te.Env); code != 0 {
		t.Fatalf("associate: %s", te.errb.String())
	}
	te.errb.Reset()
	return te, fake
}

func countCalls(fake *kpxtest.Server, action string) int {
	n := 0
	for _, c := range fake.Calls() {
		if c.Action == action {
			n++
		}
	}
	return n
}

func TestLookupPrintsNoValues(t *testing.T) {
	te, fake := lookupSetup(t, "https://x")
	if code := Main([]string{"lookup", "https://x"}, te.Env); code != 0 {
		t.Fatalf("exit %d: %s", code, te.errb.String())
	}
	out := te.out.String()
	for _, w := range []string{"hcloud s1 token", uuidA, "KPH: HCLOUD_TOKEN", "username", "group=Root/Cloud", uuidB, "totp"} {
		if !strings.Contains(out, w) {
			t.Errorf("stdout lacks %q:\n%s", w, out)
		}
	}
	for _, bad := range []string{"PW-SECRET", "FIELD-SECRET"} {
		if strings.Contains(out, bad) || strings.Contains(te.errb.String(), bad) {
			t.Errorf("value %q leaked", bad)
		}
	}
	if !strings.Contains(out, "expired") {
		t.Errorf("no expired marker:\n%s", out)
	}
	if n := countCalls(fake, "get-logins"); n != 1 {
		t.Errorf("get-logins calls = %d", n)
	}
}

