func TestFoundFieldOrder(t *testing.T) {
	got := found([]kpx.Entry{
		{UUID: "2", Name: "b", Password: "p", Login: "l", TOTP: "t", Fields: map[string]string{"KPH: Z": "1", "KPH: A": "2", "plain": "3"}},
		{UUID: "1", Name: "b", Password: "p"},
		{UUID: "0", Name: "a", Login: "l"},
	})
	if got[0].UUID != "0" || got[1].UUID != "1" || got[2].UUID != "2" {
		t.Fatalf("order: %+v", got)
	}
	if want := "password, username, totp, KPH: A, KPH: Z"; strings.Join(got[2].Fields, ", ") != want {
		t.Errorf("fields = %v", got[2].Fields)
	}
	if strings.Join(got[1].Fields, ",") != "password" {
		t.Errorf("fields = %v", got[1].Fields)
	}
}

func TestNewWritesProfile(t *testing.T) {
	te, _ := lookupSetup(t, "secure-kp://hcloud-s1")
	if code := Main([]string{"new", "hcloud-s1", "--command", "hcloud server list"}, te.Env); code != 0 {
		t.Fatalf("exit %d: %s", code, te.errb.String())
	}
	if !strings.Contains(te.errb.String(), "wrote "+filepath.Join(te.cfgDir, "hcloud-s1.toml")+"; edit it, then run: secure-kp hcloud-s1") {
		t.Errorf("stderr: %q", te.errb.String())
	}
	p, err := profile.Load(te.cfgDir, "hcloud-s1")
	if err != nil {
		t.Fatal(err)
	}
	if p.URL != "secure-kp://hcloud-s1" || strings.Join(p.Command, " ") != "hcloud server list" {
		t.Errorf("url=%q command=%v", p.URL, p.Command)
	}
	if s := p.Secrets["HCLOUD_TOKEN"]; s.UUID != uuidA || s.Field != "KPH: HCLOUD_TOKEN" {
		t.Errorf("secrets = %v", p.Secrets)
	}
	if s := p.Secrets["OLD_PASSWORD"]; s.UUID != uuidB {
		t.Errorf("secrets = %v", p.Secrets)
	}
	data, _ := os.ReadFile(filepath.Join(te.cfgDir, "hcloud-s1.toml"))
	if strings.Contains(string(data), "SECRET") {
		t.Errorf("profile contains a value:\n%s", data)
	}
	if !strings.Contains(string(data), "# generated by: secure-kp new hcloud-s1 --command hcloud server list") || !strings.Contains(string(data), " expired") {
		t.Errorf("header:\n%s", data)
	}
}

