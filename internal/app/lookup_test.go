func TestNewRejectsBadNamesBeforeConnecting(t *testing.T) {
	for _, n := range []string{"list", "new", "associate", "lookup", "../x", "a/b", ".hidden"} {
		fake := newFake()
		te := newTestEnv(t, fake)
		if code := Main([]string{"new", n}, te.Env); code != 2 {
			t.Errorf("%s: exit %d", n, code)
		}
		if len(fake.Calls()) != 0 || len(te.sockets) != 0 {
			t.Errorf("%s: connected", n)
		}
	}
	te := newTestEnv(t, newFake())
	if code := Main([]string{"new"}, te.Env); code != 2 {
		t.Errorf("no name: exit %d", code)
	}
	if code := Main([]string{"new", "a", "b"}, te.Env); code != 2 {
		t.Errorf("two names: exit %d", code)
	}
}

