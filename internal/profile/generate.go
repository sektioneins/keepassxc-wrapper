// Found describes one entry returned by a lookup. It holds no secret values.
// Fields lists the usable field names in display order.
type Found struct {
	Name, Group, UUID string
	Fields            []string
}

// GenInput is everything Generate needs to render a profile.
type GenInput struct {
	Name, URL string
	Command   []string
	Found     []Found
	Cmdline   string
	Now       time.Time
}

// VarName turns arbitrary text into an environment variable name fragment:
// upper-case, every run outside [A-Z0-9] becomes "_", "_" is trimmed at both
// ends, and a leading digit gets a "_" prefix. It may return "".
func VarName(s string) string {
	var b strings.Builder
	lastUnderscore := false
	for _, r := range strings.ToUpper(s) {
		if (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
			lastUnderscore = false
		} else if !lastUnderscore {
			b.WriteByte('_')
			lastUnderscore = true
		}
	}
	out := strings.Trim(b.String(), "_")
	if out != "" && out[0] >= '0' && out[0] <= '9' {
		out = "_" + out
	}
	return out
}

// tomlString renders s as a TOML basic string.
func tomlString(s string) string {
	s = strings.ToValidUTF8(s, "�")
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// comment makes s safe for a single TOML comment line.
func comment(s string) string {
	s = strings.ToValidUTF8(s, "�")
	return strings.Map(func(r rune) rune {
		if unicode.IsControl(r) || r == ' ' || r == ' ' {
			return ' '
		}
		return r
	}, s)
}

// Generate renders a profile file for the lookup result.
func Generate(in GenInput) ([]byte, error) {
	if err := ValidName(in.Name); err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by: %s   (%s)\n", comment(in.Cmdline), in.Now.Format("2006-01-02"))
	fmt.Fprintf(&b, "# lookup %s → %d entries\n", comment(in.URL), len(in.Found))
	for _, f := range in.Found {
		fmt.Fprintf(&b, "#   %s  group=%s  uuid=%s  fields: %s\n",
			strconv.QuoteToGraphic(comment(f.Name)), comment(f.Group), comment(f.UUID), comment(strings.Join(f.Fields, ", ")))
	}
	b.WriteString("\n")
	fmt.Fprintf(&b, "url     = %s\n", tomlString(in.URL))
	cmd := in.Command
	if len(cmd) == 0 {
		cmd = []string{Placeholder}
	}
	parts := make([]string, len(cmd))
	for i, c := range cmd {
		parts[i] = tomlString(c)
	}
	fmt.Fprintf(&b, "command = [%s]\n\n[env]\n\n[secrets]\n", strings.Join(parts, ", "))

	used := map[string]bool{}
	unique := func(base string) string {
		n := base
		for i := 2; used[n]; i++ {
			n = base + "_" + strconv.Itoa(i)
		}
		used[n] = true
		return n
	}
	for _, f := range in.Found {
		entry := VarName(f.Name)
		if entry == "" {
			entry = "ENTRY"
		}
		for _, field := range f.Fields {
			var base string
			if x, ok := strings.CutPrefix(field, "KPH: "); ok {
				if base = VarName(x); base == "" {
					base = "SECRET"
				}
			} else {
				base = entry + "_" + strings.ToUpper(field)
			}
			fmt.Fprintf(&b, "%s = { uuid = %s, field = %s }\n", unique(base), tomlString(f.UUID), tomlString(field))
		}
	}
	return []byte(b.String()), nil
}

// Write stores data as <dir>/<name>.toml, creating dir (0700) if needed. The
// file is 0600. Without force an existing file is an error; with force it is
// replaced atomically.
func Write(dir, name string, data []byte, force bool) error {
	path, err := Path(dir, name)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	if !force {
		f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
		if errors.Is(err, os.ErrExist) {
			return fmt.Errorf("profile %q already exists at %s (use --force to overwrite)", name, path)
		}
		if err != nil {
			return err
		}
		_, werr := f.Write(data)
		if cerr := f.Close(); werr == nil {
			werr = cerr
		}
		if werr != nil {
			os.Remove(path)
		}
		return werr
	}
	tmp, err := os.CreateTemp(dir, "."+name+".*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	fail := func(err error) error {
		tmp.Close()
		os.Remove(tmpName)
		return err
	}
	if err := tmp.Chmod(0o600); err != nil {
		return fail(err)
	}
	if _, err := tmp.Write(data); err != nil {
		return fail(err)
	}
	if err := tmp.Sync(); err != nil {
		return fail(err)
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmpName)
		return err
	}
	if err := os.Rename(tmpName, filepath.Join(dir, name+".toml")); err != nil {
		os.Remove(tmpName)
		return err
	}
	return nil
}
