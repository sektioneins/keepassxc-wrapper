func TestVarName(t *testing.T) {
	for in, want := range map[string]string{
		"hcloud s1 token": "HCLOUD_S1_TOKEN",
		"  --x--":         "X",
		"1st key":         "_1ST_KEY",
		"Grüße":           "GR_E",
		"":                "",
		"ßß":              "",
	} {
		if got := VarName(in); got != want {
			t.Errorf("VarName(%q) = %q, want %q", in, got, want)
		}
	}
}

func genAndLoad(t *testing.T, in GenInput) (*Profile, string) {
	t.Helper()
	data, err := Generate(in)
	if err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join(t.TempDir(), "cfg")
	if err := Write(dir, in.Name, data, false); err != nil {
		t.Fatal(err)
	}
	p, err := Load(dir, in.Name)
	if err != nil {
		t.Fatalf("Load: %v\n%s", err, data)
	}
	return p, string(data)
}

func TestGenerateRoundTrip(t *testing.T) {
	p, out := genAndLoad(t, GenInput{
		Name: "hcloud-s1", URL: "secure-kp://hcloud-s1",
		Found: []Found{
			{Name: "hcloud s1 token", Group: "Root/Cloud", UUID: u1, Fields: []string{"password", "KPH: HCLOUD_TOKEN"}},
			{Name: "hcloud s1 ssh", Group: "Root", UUID: u2, Fields: []string{"password"}},
		},
		Cmdline: "secure-kp new hcloud-s1",
		Now:     time.Date(2026, 11, 2, 10, 0, 0, 0, time.UTC),
	})
	want := map[string]Secret{
		"HCLOUD_TOKEN":             {u1, "KPH: HCLOUD_TOKEN"},
		"HCLOUD_S1_TOKEN_PASSWORD": {u1, "password"},
		"HCLOUD_S1_SSH_PASSWORD":   {u2, "password"},
	}
	if !reflect.DeepEqual(p.Secrets, want) {
		t.Errorf("secrets = %v", p.Secrets)
	}
	if !reflect.DeepEqual(p.Command, []string{"CHANGE-ME"}) || p.Runnable() == nil {
		t.Errorf("command = %v", p.Command)
	}
	if p.URL != "secure-kp://hcloud-s1" {
		t.Errorf("url = %q", p.URL)
	}
	for _, s := range []string{"# generated by: secure-kp new hcloud-s1   (2026-11-02)", "# lookup secure-kp://hcloud-s1 → 2 entries", "uuid=" + u1} {
		if !strings.Contains(out, s) {
			t.Errorf("output lacks %q:\n%s", s, out)
		}
	}
}

func TestGenerateCommand(t *testing.T) {
	p, _ := genAndLoad(t, GenInput{Name: "x", URL: "u", Command: []string{"hcloud", "server"},
		Found: []Found{{Name: "e", UUID: u1, Fields: []string{"password", "username", "totp"}}}})
	if !reflect.DeepEqual(p.Command, []string{"hcloud", "server"}) || p.Runnable() != nil {
		t.Errorf("command = %v", p.Command)
	}
	for _, k := range []string{"E_PASSWORD", "E_USERNAME", "E_TOTP"} {
		if _, ok := p.Secrets[k]; !ok {
			t.Errorf("missing %s: %v", k, p.Secrets)
		}
	}
}

func TestGenerateCollisions(t *testing.T) {
	p, _ := genAndLoad(t, GenInput{Name: "x", URL: "u", Found: []Found{
		{Name: "api", UUID: u1, Fields: []string{"password"}},
		{Name: "api", UUID: u2, Fields: []string{"password", "KPH: API_PASSWORD_2"}},
		{Name: "", UUID: u2, Fields: []string{"password", "KPH: ßß"}},
	}})
	want := map[string]Secret{
		"API_PASSWORD":     {u1, "password"},
		"API_PASSWORD_2":   {u2, "password"},
		"API_PASSWORD_2_2": {u2, "KPH: API_PASSWORD_2"},
		"ENTRY_PASSWORD":   {u2, "password"},
		"SECRET":           {u2, "KPH: ßß"},
	}
	if !reflect.DeepEqual(p.Secrets, want) {
		t.Errorf("secrets = %v", p.Secrets)
	}
}

func TestGenerateHostileEntryName(t *testing.T) {
	p, out := genAndLoad(t, GenInput{Name: "x", URL: "u\"v\nw", Cmdline: "a\nb", Found: []Found{
		{Name: "a\"b\nc\r\x01", Group: "g\nh", UUID: u1, Fields: []string{"password", "KPH: q\"r\nz"}},
	}})
	if len(p.Secrets) != 2 || p.URL != "u\"v\nw" {
		t.Errorf("secrets=%v url=%q\n%s", p.Secrets, p.URL, out)
	}
	if p.Secrets["Z"].Field != "KPH: q\"r\nz" && p.Secrets["Q_R_Z"].Field != "KPH: q\"r\nz" {
		t.Errorf("secrets = %v", p.Secrets)
	}
}

