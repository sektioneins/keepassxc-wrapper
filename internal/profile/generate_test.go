func TestWriteRefusesOverwrite(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "cfg")
	if err := Write(dir, "p", []byte("a"), false); err != nil {
		t.Fatal(err)
	}
	err := Write(dir, "p", []byte("b"), false)
	if err == nil || !strings.Contains(err.Error(), "--force") {
		t.Fatalf("err = %v", err)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "p.toml")); string(b) != "a" {
		t.Errorf("content = %q", b)
	}
	if err := Write(dir, "p", []byte("c"), true); err != nil {
		t.Fatal(err)
	}
	fi, _ := os.Stat(filepath.Join(dir, "p.toml"))
	di, _ := os.Stat(dir)
	if b, _ := os.ReadFile(filepath.Join(dir, "p.toml")); string(b) != "c" {
		t.Errorf("content = %q", b)
	}
	if fi.Mode().Perm() != 0o600 || di.Mode().Perm() != 0o700 {
		t.Errorf("modes %v %v", fi.Mode().Perm(), di.Mode().Perm())
	}
	ents, _ := os.ReadDir(dir)
	if len(ents) != 1 {
		t.Errorf("leftover files: %v", ents)
	}
	if err := Write(dir, "../x", []byte("c"), true); err == nil {
		t.Error("want error for bad name")
	}
}

func TestWriteKeepsLooseDir(t *testing.T) {
	dir := t.TempDir()
	if err := os.Chmod(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := Write(dir, "p", []byte("a"), true); err != nil {
		t.Fatal(err)
	}
	if di, _ := os.Stat(dir); di.Mode().Perm() != 0o755 {
		t.Errorf("dir mode = %v", di.Mode().Perm())
	}
}
